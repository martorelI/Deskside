namespace Deckside.Core.Settings;

/// <summary>
/// Contents of <c>Settings/settings.json</c>. Credentials are never part of it (security rule 5).
/// Defaults are placeholders: the OUs and domain are empty until the operator configures them, and every
/// operation that writes refuses to run while they are empty.
/// </summary>
public sealed record AppSettings
{
    public string Language { get; init; } = "es";

    /// <summary>Folder for settings, evidence and reports. Empty = next to Deckside.exe.</summary>
    public string DataFolder { get; init; } = "";

    /// <summary>
    /// The only part of the directory Deckside may change. Every other OU of the settings must be inside it,
    /// and every write (objects, moves, group memberships) is checked against it, in the planners and again
    /// in the directory layer right before sending the request. Empty = nothing can be written.
    /// </summary>
    public string MasterOU { get; init; } = "";

    /// <summary>DNS name of the domain, e.g. <c>example.local</c>. Empty = taken from the DC= parts of <see cref="MasterOU"/>.</summary>
    public string Domain { get; init; } = "";

    /// <summary>Where the requests go: IP address (preferred) or host name of a domain controller.</summary>
    public string Server { get; init; } = "";

    /// <summary>LDAP port. 0 = default (389, or 636 with LDAPS).</summary>
    public int Port { get; init; }

    /// <summary>true = LDAPS; false = LDAP with signing and sealing (Kerberos or NTLM). Never unencrypted.</summary>
    public bool UseLdaps { get; init; }

    /// <summary>Domain used for UPN / e-mail defaults: <see cref="Domain"/>, or the one of <see cref="MasterOU"/>.</summary>
    public string EffectiveDomain =>
        Domain.Length > 0 ? Domain : Directory.DistinguishedName.IsValid(MasterOU) ? Directory.DistinguishedName.DomainOf(MasterOU) : "";

    public string UsersOU { get; init; } = "";

    public string ComputersOU { get; init; } = "";

    public string DisabledOU { get; init; } = "";

    /// <summary>Whether objects in sub-OUs of the users / computers OU are in scope (TBD with the owner).</summary>
    public bool IncludeSubOUs { get; init; } = true;

    /// <summary>Every write (create, offboarding, profile) needs a ticket number.</summary>
    public bool RequireTicket { get; init; } = true;

    public NamingSettings Naming { get; init; } = new();

    public PasswordSettings Password { get; init; } = new();

    public OffboardingSettings Offboarding { get; init; } = new();

    public ReportSettings Report { get; init; } = new();

    /// <summary>DNs of the groups proposed for every new computer.</summary>
    public IReadOnlyList<string> DefaultComputerGroups { get; init; } = [];

    /// <summary>sAMAccountNames of extra groups to treat as protected. It can only add protection, never remove it.</summary>
    public IReadOnlyList<string> ExtraProtectedGroups { get; init; } = [];

    /// <summary>Profiles file, relative to the data folder.</summary>
    public string ProfilesFile { get; init; } = "Profiles/profiles.json";
}

public sealed record NamingSettings
{
    public string SamPattern { get; init; } = "U{seq:5}";

    public long SamFirstNumber { get; init; } = 1;

    public string ComputerPattern { get; init; } = "PC{seq:5}";

    public long ComputerFirstNumber { get; init; } = 1;

    public string MailPattern { get; init; } = "{given1}.{surname1}";

    public IReadOnlyList<string> MailFallbacks { get; init; } = ["{given1}.{surname1}{s2}", "{given1}.{surname1}{n}"];

    /// <summary>E-mail domain. Empty = <see cref="AppSettings.Domain"/>.</summary>
    public string MailDomain { get; init; } = "";

    /// <summary>Also write <c>proxyAddresses</c> = <c>SMTP:address</c> (only when the mail system reads it from AD).</summary>
    public bool SetProxyAddresses { get; init; }

    public string UpnPattern { get; init; } = "{sam}@{upnSuffix}";

    /// <summary>UPN suffix. Empty = <see cref="AppSettings.Domain"/>.</summary>
    public string UpnSuffix { get; init; } = "";

    public string CnPattern { get; init; } = "{Given} {Surnames}";

    public string DisplayNamePattern { get; init; } = "{Given} {Surnames}";

    /// <summary>What goes in <c>sn</c>: both surnames by default.</summary>
    public string SurnamePattern { get; init; } = "{Surnames}";
}

public sealed record PasswordSettings
{
    /// <summary>true = generated by Deckside; false = typed by the operator.</summary>
    public bool Generate { get; init; } = true;

    public int Length { get; init; } = 16;

    /// <summary>Minimum length accepted for a typed password (the domain policy may ask for more).</summary>
    public int MinimumLength { get; init; } = 12;
}

public sealed record OffboardingSettings
{
    /// <summary>Tokens: {date} {ticket} {reason} {operator} {previous}.</summary>
    public string DescriptionPattern { get; init; } = "Disabled {date} | {ticket} | {reason} | {operator}";
}

public sealed record ReportSettings
{
    public int InactiveDays { get; init; } = 90;

    public int ExpiryWarningDays { get; init; } = 14;

    public int BadPasswordThreshold { get; init; } = 3;

    /// <summary>Computers change their password every 30 days by default; older means the machine is gone or broken.</summary>
    public int MachinePasswordMaxDays { get; init; } = 60;

    /// <summary>Read <c>lastLogon</c> / <c>badPwdCount</c> from every DC (slower) instead of only the PDC emulator.</summary>
    public bool QueryAllDCs { get; init; }
}
